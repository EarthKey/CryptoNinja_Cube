const cdp=await page.context().newCDPSession(page);
await cdp.send('Input.dispatchTouchEvent',{type:'touchStart',touchPoints:[{x:tile.x,y:tile.y}]});
await page.waitForTimeout(250);
await cdp.send('Input.dispatchTouchEvent',{type:'touchMove',touchPoints:[{x:tile.x+60,y:tile.y}]});
await cdp.send('Input.dispatchTouchEvent',{type:'touchEnd',touchPoints:[]});
