await page.getByRole('button',{name:'最初に戻す'}).click();
await page.waitForTimeout(350);
assert.equal((await snap()).busy,false);
assert.equal((await snap()).history,0,'reset cancels queued animation');
await page.getByRole('button',{name:'最初に戻す'}).click();await page.waitForTimeout(300);
assert.deepEqual((await snap()).pieces,initial);
await page.screenshot({path:'desktop-check.png'});
const desktop=await snap();
for(const keys of [['w','s'],['a','d'],['w','w','w','w'],['a','a','a','a']]){
 const target=await page.evaluate(()=>window.__cube.tilePoint(0,7));
 await page.mouse.click(target.x,target.y);
 for(const key of keys){await page.keyboard.press(key);await page.waitForTimeout(300);}
 assert.deepEqual((await snap()).pieces,initial,'fixed selection: '+keys.join(''));
}
