assert.equal((await snap()).history,1,'long press swipe');
await page.getByRole('button',{name:'採用イラストを見る'}).click();
await page.keyboard.press('w');await page.waitForTimeout(300);
assert.equal((await snap()).history,1,'modal blocks game keyboard');
