import {chromium} from '@playwright/test';
import assert from 'node:assert/strict';
const browser=await chromium.launch({channel:'msedge',headless:true});
const page=await browser.newPage({viewport:{width:1280,height:1000}});
const errors=[];page.on('pageerror',e=>errors.push(e.message));
await page.goto('http://127.0.0.1:5173/');
await page.waitForFunction(()=>window.__cube?.snapshot().fps>0);
await page.getByRole('button',{name:'6面完成',exact:true}).click();
const snap=()=>page.evaluate(()=>window.__cube.snapshot());
const initial=(await snap()).pieces;
const point=await page.evaluate(()=>window.__cube.tilePoint(0,7));
await page.mouse.click(point.x,point.y);
assert.ok((await snap()).selection,'pointer picks tile');
await page.keyboard.press('w');await page.waitForTimeout(350);
assert.equal((await snap()).history,1);
assert.notDeepEqual((await snap()).pieces,initial);
await page.getByRole('button',{name:'1手戻す'}).click();await page.waitForTimeout(800);
assert.deepEqual((await snap()).pieces,initial);
assert.equal((await snap()).solved.length,6);
assert.ok((await snap()).spacing<1.01);
await page.getByRole('button',{name:'3手だけ混ぜる'}).click();await page.waitForTimeout(950);
assert.equal((await snap()).history,3);
const rotatedTile=await page.evaluate(()=>window.__cube.tilePoint(0,7));
await page.mouse.click(rotatedTile.x,rotatedTile.y);
await page.getByRole('button',{name:'最初に戻す'}).click();
